export const passagesById: Record<string, Passage> = Object.fromEntries(
  passages.map((p) => [p.id, p]),
);

export function getPassage(id: string): Passage | undefined {
  return passagesById[id];
}

/** Texte continu d'un passage, utile pour le partage et la lecture suivie. */
export function passageText(p: Passage): string {
  return p.verses.map((v) => v.t).join(' ');
}

